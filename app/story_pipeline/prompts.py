def format_page_numbers(numbers: list[int]) -> str:
    """Собрать номера страниц в строку «1, 2, 3» для текста промпта."""

    return ", ".join(str(number) for number in numbers)


def duplicate_page_numbers(numbers: list[int]) -> list[int]:
    """Вернуть отсортированные номера, встречающиеся в списке больше раза.

    Чистая функция без LLM и I/O, общая для валидаторов страниц и сцен: дубль
    номера означает, что на одну страницу пришлось два разных артефакта.
    """

    return sorted({number for number in numbers if numbers.count(number) > 1})


def format_pages(pages: list[PageText]) -> str:
    """Собрать текст страниц в нумерованный блок для промпта."""

    return "\n".join(
        f"Страница {page.page_num}: {page.text}" for page in pages
    )


def format_issues(issues: list[str]) -> str:
    """Собрать замечания судьи в маркированный список для промпта ревизора.

    Пустой список — тоже валидный вход (например, остались только
    нерешённые ссылки сцен): тогда явно сообщаем, что замечаний нет, чтобы
    модель не додумывала их сама.
    """

    if not issues:
        return "- Замечаний не указано: проверь проблемные страницы на месте."
    return "\n".join(f"- {issue}" for issue in issues)


def format_entity_registry(entities: ExtractedEntities) -> str:
    """Собрать реестр сущностей с описаниями в текстовый блок промпта.

    Персонажи даны вместе с дословным `full_desc`: этот же текст является
    якорем внешности в промптах изображений.
    """

    characters = "\n".join(
        f"- {character.name}: {character.full_desc}"
        for character in entities.characters
    )
    locations = "\n".join(
        f"- {location.name}: {location.description}"
        for location in entities.locations
    )
    objects = "\n".join(
        f"- {item.name}: {item.description}" for item in entities.key_objects
    )
    return (
        f"Единый стиль иллюстраций: {entities.art_style}\n"
        f"Персонажи:\n{characters}\n"
        f"Локации:\n{locations}\n"
        f"Ключевые объекты:\n{objects}"
    )


def format_scene_violations(violations: list[SceneRefViolation]) -> str:
    """Собрать список нарушений ссылок сцен в текстовый блок промпта.

    Группирует нарушения по проблемным страницам, чтобы перезапрос был
    адресным: страница → поле → неверное значение.
    """

    by_page: dict[int, list[SceneRefViolation]] = {}
    for violation in violations:
        by_page.setdefault(violation.page_num, []).append(violation)
    lines: list[str] = []
    for page_num in sorted(by_page):
        details = "; ".join(
            f"{violation.field} = «{violation.value}»"
            for violation in by_page[page_num]
        )
        lines.append(f"Страница {page_num}: {details}")
    return "\n".join(lines)


def format_scene_pages(
    scenes: list[PageScene],
    pages: list[PageText],
) -> str:
    """Собрать сцены вместе с текстом их страниц в единый блок промпта.

    Формат общий для трёх потребителей: корректирующий перезапрос
    раскадровки видит исходную композицию кадра и действие страницы, судья
    проверяет соответствие текста и сцены, ревизор правит только
    проблемные страницы. Текст страницы и сцена идут парой, чтобы
    адресность правки не зависела от сопоставления по номеру.
    """

    texts = {page.page_num: page.text for page in pages}
    blocks: list[str] = []
    for scene in scenes:
        characters = ", ".join(scene.characters_in_scene) or "нет"
        objects = ", ".join(scene.objects_in_scene) or "нет"
        blocks.append(
            f"Страница {scene.page_num}.\n"
            f"Текст страницы: {texts.get(scene.page_num, '')}\n"
            f"Текущая сцена: {scene.scene_description}\n"
            f"Персонажи: {characters}\n"
            f"Локация: {scene.location}\n"
            f"Объекты: {objects}"
        )
    return "\n\n".join(blocks)


def _beat_page_ranges(num_pages: int) -> list[str]:
    """Разбить страницы 1..N на четыре бита арки как можно ровнее.

    Остаток от деления распределяется по первым битам, поэтому при N=6
    получаются диапазоны «1–2», «3–4», «5», «6». Для пустого бита
    возвращается «нет».
    """

    quotient, remainder = divmod(max(num_pages, 0), 4)
    sizes = [quotient + (1 if i < remainder else 0) for i in range(4)]
    ranges: list[str] = []
    start = 1
    for size in sizes:
        if size <= 0:
            ranges.append("нет")
            continue
        end = start + size - 1
        ranges.append(str(start) if start == end else f"{start}–{end}")
        start = end + 1
    return ranges


def format_arc_plan(arc: NarrativeArc, num_pages: int) -> str:
    """Собрать инструкцию о привязке диапазонов страниц к битам арки."""

    exposition, rising, climax, resolution = _beat_page_ranges(num_pages)
    return "\n".join(
        (
            f"Завязка (страницы {exposition}): {arc.exposition}",
            f"Нарастание (страницы {rising}): {arc.rising_action}",
            f"Кульминация (страницы {climax}): {arc.climax}",
            f"Развязка (страницы {resolution}): {arc.resolution}",
        )
    )
