def format_illustration_plan(
    illustrated_pages: list[int],
    num_pages: int,
) -> str:
    """Блок промпта сценариста про набор иллюстрируемых страниц.

    При наборе, равном всем страницам, возвращается нынешняя формулировка про
    иллюстрируемость каждой страницы: при полном наборе ограничения нет, и
    текст для обычного прогона стал бы хуже без неё. Отдельная ветка, а не
    вывод из общего шаблона, — требования противоположны.

    Пустой набор трактуется как «не задан» и даёт полный: тот же смысл
    пустого поля в состоянии прогона (`resolve_illustrated_pages`).
    """

    if not illustrated_pages or set(illustrated_pages) >= set(
        range(1, num_pages + 1)
    ):
        return ALL_PAGES_ILLUSTRATABLE
    return ILLUSTRATED_PAGES_PLAN.format(
        pages=format_page_numbers(sorted(illustrated_pages))
    )


