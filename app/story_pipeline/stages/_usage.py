"""Общий хелпер накопления токенов нескольких попыток этапа.

Модуль приватный (`_usage`): это внутренняя деталь этапов пайплайна, а не
публичный контракт пакета. Размещён в `stages/`, потому что складывать
расход повторных вызовов приходится именно этапам, которые делают
корректирующие перезапросы; вынос в `providers/` смешал бы его с
транспортом LLM, а в `models.py` — с моделями состояния.
"""

from __future__ import annotations


def add_tokens(total: int | None, value: int | None) -> int | None:
    """Сложить токены двух попыток, сохраняя `None` как «неизвестно».

    Если очередная попытка не вернула расход (`None`), итог не обнуляется:
    «неизвестно» не должно затирать уже посчитанное.
    """

    if value is None:
        return total
    return (total or 0) + value


__all__ = ["add_tokens"]
